// The pool id is interpolated into the AWS discovery URL whose response supplies the
// `authorization_endpoint` — the page where a user types their password.
//
// So the tests that matter here are the ones proving a malformed id cannot MOVE that URL.
// If the "could redirect discovery" block is ever relaxed, a hostile pool id can send users
// to a login page of its own choosing, and the whole reason the endpoints come from AWS
// rather than from a server is defeated.

import { describe, it, expect } from "vitest";
import {
  oidcDiscoveryUrl,
  regionFromPoolId,
  isValidPoolId,
  CognitoPoolError,
} from "./cognito-pool";

const POOL = "us-east-1_EXAMPLE01";

describe("oidcDiscoveryUrl", () => {
  it("builds AWS's discovery URL for the pool's own region", () => {
    expect(oidcDiscoveryUrl(POOL)).toBe(
      "https://cognito-idp.us-east-1.amazonaws.com/us-east-1_EXAMPLE01/.well-known/openid-configuration"
    );
    expect(oidcDiscoveryUrl("eu-west-2_AbC123")).toBe(
      "https://cognito-idp.eu-west-2.amazonaws.com/eu-west-2_AbC123/.well-known/openid-configuration"
    );
  });

  it("tolerates surrounding whitespace", () => {
    expect(oidcDiscoveryUrl(`  ${POOL}  `)).toContain(POOL);
  });

  /**
   * ⚠ THE ATTACK THIS FUNCTION MUST BE IMMUNE TO.
   *
   * Each of these, if interpolated unvalidated, would point discovery — and therefore the
   * login page — at a host the caller chose. Validation lives HERE, with the URL
   * construction, rather than in a caller that has "already checked", because this is the
   * last place that can guarantee it.
   */
  it.each([
    "x/../../evil.example/",
    "us-east-1_A/../../../evil.example/x",
    "evil.example/us-east-1_Abc",
    "https://evil.example",
    "us-east-1_Abc@evil.example",
    "us-east-1_Abc#frag",
    "us-east-1_Abc?x=1",
    "us-east-1_Abc/extra",
    "us-east-1_Abc%2F..%2Fevil",
    "..",
    "",
    "   ",
  ])("rejects a pool id that could redirect discovery: %s", (poolId) => {
    expect(() => oidcDiscoveryUrl(poolId)).toThrow(CognitoPoolError);
  });

  it("rejects a pool id whose region shape is wrong", () => {
    expect(() => oidcDiscoveryUrl("useast1_Abc")).toThrow(CognitoPoolError);
    expect(() => oidcDiscoveryUrl("_Abc")).toThrow(CognitoPoolError);
    expect(() => oidcDiscoveryUrl("us-east-1_")).toThrow(CognitoPoolError);
    expect(() => oidcDiscoveryUrl("us-east_Abc")).toThrow(CognitoPoolError);
  });

  it("accepts a region that did not exist when this shipped", () => {
    // Matched as a SHAPE, not against a list, so a new AWS region needs no desktop release.
    expect(() => oidcDiscoveryUrl("xx-north-9_Abc123")).not.toThrow();
  });
});

describe("regionFromPoolId", () => {
  it("derives the region from the id rather than taking it separately", () => {
    // Two fields that must agree are a way for them to disagree.
    expect(regionFromPoolId(POOL)).toBe("us-east-1");
    expect(regionFromPoolId("ap-southeast-2_Xyz9")).toBe("ap-southeast-2");
  });
});

describe("isValidPoolId", () => {
  it("accepts real pool ids and rejects the traversal shapes", () => {
    expect(isValidPoolId(POOL)).toBe(true);
    expect(isValidPoolId("x/../evil")).toBe(false);
    expect(isValidPoolId("")).toBe(false);
  });

  it("is case-sensitive on the SUFFIX, which Cognito is", () => {
    // The suffix is generated by Cognito and case matters; folding it would make two
    // genuinely different pools look like one.
    expect(isValidPoolId("us-east-1_AbC")).toBe(true);
    // The region prefix, by contrast, is always lower-case.
    expect(isValidPoolId("US-EAST-1_AbC")).toBe(false);
  });
});
