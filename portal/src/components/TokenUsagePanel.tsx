"use client";

// ── ⚠ TOKEN USAGE, AND WHETHER IT COULD BE BETTER ────────────────────────────────────────
//
// Usage stats, and whether efficiency can be improved.
//
// The arithmetic and the signals are in `lib/token-insights.ts`, kept pure so the honesty rules are tested
// rather than asserted. This file is the presentation, and it has three jobs beyond drawing boxes:
//
//   ⚠ 1. RENDER NOTHING WHEN NOTHING WAS MEASURED. Only Codex reports usage; Claude's spawn path and Kiro
//        report none, and every turn from before the feature has none either. A panel showing "0 tokens · 0%
//        cached" on a team that worked all day would be a confident lie, and this page is read by executives.
//
//   ⚠ 2. SAY WHAT IT DOES NOT KNOW. Coverage travels with the figures: "over 14 of 22 replies" is the
//        difference between a total and a floor, and the reader cannot infer it.
//
//   ⚠ 3. STAY VISUALLY SEPARATE FROM THE RATING BLOCKS. This sits on the same page as a model-written
//        assessment of named people. A number next to that READS as part of the assessment even when it is
//        not, so this is labelled as efficiency data, uses neutral ink rather than the rating palette, and
//        never grades anybody — judgements carry a real cost here.

import { computeTokenInsights, type ThreadTokens } from "@/lib/token-insights";

/**
 * ⚠ THE PER-PERSON TABLE IS OFF: the token comparison table is hidden for now, BACKLOG 9a, where
 * what has to be true before it returns is written down. A constant rather than a prop: nothing should be
 * able to switch this on per-caller while the figures are still incomparable across assistants.
 */
const SHOW_PER_PERSON = false;

/** Compact count: `931`, `13.0k`, `1.2M`. The precise figure goes in the `title`. */
function human(n: number): string {
  if (!Number.isFinite(n) || n < 0) return "-";
  if (n < 1000) return String(Math.round(n));
  if (n < 1_000_000) return `${(n / 1000).toFixed(n < 10_000 ? 1 : 0)}k`;
  return `${(n / 1_000_000).toFixed(1)}M`;
}

export function TokenUsagePanel({
  threads,
  truncated = false,
  totalThreads,
  nameByUserId,
}: {
  threads: ThreadTokens[];
  truncated?: boolean;
  totalThreads?: number;
  /** Display names, so a row shows a person rather than an id. Absent ids are skipped, never guessed. */
  nameByUserId?: Map<string, string>;
}) {
  const insights = computeTokenInsights(threads);

  /** Rule 1: nothing measured, nothing shown. Not a zero, not an empty state, absent. */
  if (insights.empty) return null;

  return (
    <section className="rounded-lg border bg-surface-3 p-5" aria-labelledby="token-usage-heading">
      <div className="flex items-baseline justify-between gap-3">
        <h3 id="token-usage-heading" className="text-sm font-semibold text-ink-muted">
          Token usage
        </h3>
        {/* Rule 3: says plainly what kind of number this is, so it is not read as part of an assessment. */}
        <p className="text-xs text-ink-tertiary">Efficiency, not assessment</p>
      </div>

      <dl className="mt-4 grid grid-cols-2 gap-4 sm:grid-cols-4">
        <Stat
          label="Context sent"
          value={human(insights.inputTokens)}
          title={
            `${insights.inputTokens.toLocaleString()} tokens of context across ${insights.counted} ` +
            `replies. Each turn re-sends the conversation so far, so this re-counts earlier turns, it is ` +
            `what was SENT, not what anyone wrote.`
          }
        />
        <Stat
          label="Generated"
          value={human(insights.outputTokens)}
          title={`${insights.outputTokens.toLocaleString()} tokens generated by the assistant.`}
        />
        {insights.cacheRate !== null && (
          <Stat
            label="Served from cache"
            value={`${insights.cacheRate}%`}
            tone="text-success-text"
            title={
              `${insights.cachedInputTokens.toLocaleString()} of ${insights.inputTokens.toLocaleString()} ` +
              `prompt tokens were read from cache rather than re-sent.`
            }
          />
        )}
        <Stat
          label="Conversations"
          value={String(insights.threads)}
          title={`${insights.threads} conversations, ${insights.replies} assistant replies in total.`}
        />
      </dl>

      {/*
        ⚠ THE TREND IS THE TEAM'S OWN, WHICH IS WHY IT CAN BE SHOWN AT ALL. We rejected absolute
        thresholds ("under 50% is bad") and cross-team comparison; a team measured against itself needs no
        benchmark and cannot become a league table.
      */}
      {insights.trend && (
        <p className="mt-4 text-sm text-ink-muted">
          Cache reuse moved from{" "}
          <span className="font-medium tabular-nums">{insights.trend.older}%</span> across the earlier
          conversations to{" "}
          <span className="font-medium tabular-nums">{insights.trend.newer}%</span> in the later ones
          {insights.trend.delta !== 0 && (
            <span className={insights.trend.delta > 0 ? "text-success-text" : "text-warn-text"}>
              {" "}
              ({insights.trend.delta > 0 ? "+" : ""}
              {insights.trend.delta} points)
            </span>
          )}
          .
        </p>
      )}

      {/*
        ── ⚠ PER PERSON, AND WHAT THAT CAN HONESTLY CLAIM ────────────────────────────────────
        Individual token usage per user, on the insights page.

        ⚠ THE HEADING SAYS "conversations they started", NOT "tokens they used", because that is the only
        attribution the data supports: the counts live on the ASSISTANT messages, which carry no user id, so a
        thread's usage can only be credited to its OWNER. Somebody who contributed turns to a colleague's
        thread appears nowhere in their own row.

        ⚠ AND IT IS NOT SORTED BY AMOUNT. Ordering people by consumption is a leaderboard, which we
        rejected for teams and which is worse per person, this table sits beside a model-written
        assessment of the same names. Sorted alphabetically, so the order carries no verdict.
      */}
      {/*
        ── ⚠ HIDDEN, NOT DELETED ──

        The token comparison table is hidden for now and parked on the backlog, BACKLOG 9a.

        ⚠ THE REASON IT IS PARKED IS A REAL MEASUREMENT PROBLEM, not a preference, and it is worth stating
        where the flag is rather than only in the backlog. A row per person invites comparison between them,
        and the figures are not comparable:

          • the assistants disagree by orders of magnitude, one real Codex turn in the field reported 13.2M
            context tokens, where a Claude turn reports tens of thousands, and `computeTokenInsights` sums
            them into one column regardless of provider
          • coverage varies per provider, Kiro reports nothing at all, so its participants read as light
            users when they may be the heaviest
          • attribution is by thread OWNER, since the counts live on assistant rows that carry no user id, so
            somebody who worked in a colleague's thread contributes to that colleague's row

        Kept as one flag rather than a deletion: `perPerson` and its tests are correct and paid for, and this
        page's totals still depend on the same aggregate. Delete the flag to restore it.
      */}
      {SHOW_PER_PERSON && insights.perPerson.length > 0 && (
        <div className="mt-4 border-t pt-4">
          <h4 className="text-xs font-semibold uppercase tracking-wide text-ink-subtle">
            By conversations they started
          </h4>
          <table className="mt-2 w-full text-sm">
            <thead>
              <tr className="text-left text-xs text-ink-subtle">
                <th scope="col" className="pb-1 font-normal">Participant</th>
                <th scope="col" className="pb-1 text-right font-normal">Context</th>
                <th scope="col" className="pb-1 text-right font-normal">Generated</th>
                <th scope="col" className="pb-1 text-right font-normal">Cached</th>
              </tr>
            </thead>
            <tbody>
              {insights.perPerson
                /* Display order only, the data itself is not ranked. */
                .slice()
                .sort((a, b) =>
                  (nameByUserId?.get(a.userId) ?? a.userId).localeCompare(
                    nameByUserId?.get(b.userId) ?? b.userId
                  )
                )
                .map((p) => (
                  <tr key={p.userId} className="border-t border-hairline-soft">
                    <td className="py-1 pr-2 text-ink-muted">
                      {nameByUserId?.get(p.userId) ?? "Unknown participant"}
                      <span className="ml-1 text-xs text-ink-tertiary">
                        · {p.threads} {p.threads === 1 ? "conversation" : "conversations"}
                      </span>
                    </td>
                    <td className="py-1 text-right tabular-nums text-ink-muted">{human(p.inputTokens)}</td>
                    <td className="py-1 text-right tabular-nums text-ink-muted">{human(p.outputTokens)}</td>
                    <td className="py-1 text-right tabular-nums text-ink-muted">
                      {/* Absent rather than 0% when this person's threads reported no cache split. */}
                      {p.cacheRate === null ? "-" : `${p.cacheRate}%`}
                    </td>
                  </tr>
                ))}
            </tbody>
          </table>
          <p className="mt-2 text-xs text-ink-subtle">
            Attributed to whoever started each conversation. Turns contributed to someone else&apos;s
            conversation are not counted here.
          </p>
        </div>
      )}

      {insights.signals.length > 0 && (
        <ul className="mt-4 space-y-2 border-t pt-4">
          {insights.signals.map((s) => (
            <li key={s.id} className="text-sm">
              <span className="text-ink-muted">{s.fact}</span>
              {/* The action is the coaching. Absent when the fact is simply context. */}
              {s.action && <span className="text-ink-subtle"> {s.action}</span>}
            </li>
          ))}
        </ul>
      )}

      {/*
        Rule 2. Two separate incompletenesses, and they are different facts: replies nobody counted, and
        threads this figure never looked at.
      */}
      {(insights.counted < insights.replies || truncated) && (
        <p className="mt-4 border-t pt-3 text-xs text-ink-subtle">
          {insights.counted < insights.replies && (
            <>
              Measured over {insights.counted} of {insights.replies} replies, the rest carry no counts, so
              these are minimums.{" "}
            </>
          )}
          {truncated && (
            <>Only the most recent 25 of {totalThreads ?? "many"} conversations were included.</>
          )}
        </p>
      )}
    </section>
  );
}

function Stat({
  label,
  value,
  title,
  tone = "text-ink",
}: {
  label: string;
  value: string;
  title: string;
  tone?: string;
}) {
  return (
    <div>
      <dt className="text-xs text-ink-subtle">{label}</dt>
      {/* `title` on the value, where the pointer naturally lands, and it carries the exact figure. */}
      <dd className={`mt-0.5 text-lg font-semibold tabular-nums ${tone}`} title={title}>
        {value}
      </dd>
    </div>
  );
}
